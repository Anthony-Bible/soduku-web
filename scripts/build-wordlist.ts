/**
 * Builds the Lettergrid Word List artifact from SCOWL exports.
 *
 *   pnpm wordlist <size-60-export.txt> <size-35-export.txt> <esdb-scowl-pre.txt> <esdb-revision>
 *
 * The size-60 export is the Word List; the size-35 export (common words) limits Seed Word
 * candidates. scowl-pre.txt (data/ in the ESDB repo at the same revision) says which entries are
 * abbreviations. <esdb-revision> is the ESDB git revision of all three inputs (recorded in the artifact).
 * Writes public/lettergrid/wordlist-v<N>.txt and src/core/lettergrid/letterValuesV<N>.ts; the new
 * version must then be registered by hand in src/core/lettergrid/letterValuesTable.ts.
 * Regenerating from the same inputs gives byte-identical output.
 */
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { extractAbbreviations, filterScowlWords, pickSeedCandidates } from '../src/core/lettergrid/filter'
import { deriveLetterValues, deriveTileWeights } from '../src/core/lettergrid/letterValues'
import { CURRENT_WORD_LIST_VERSION, wordListPath } from '../src/core/lettergrid/wordList'
import { encodeWordList } from '../src/core/lettergrid/wordlistFormat'

const [bigPath, commonPath, prePath, esdbRevision] = process.argv.slice(2)
if (!bigPath || !commonPath || !prePath || !esdbRevision || !/^[0-9a-f]{7,40}$/.test(esdbRevision)) {
  console.error('usage: pnpm wordlist <scowl-size-60.txt> <scowl-size-35.txt> <esdb-scowl-pre.txt> <esdb-git-revision>')
  process.exit(1)
}
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const text = (path: string) => readFileSync(path, 'utf8')
const lines = (path: string) => text(path).split('\n')
const sha = (path: string) => createHash('sha256').update(readFileSync(path)).digest('hex')

// A published version is frozen (ADR 0003): never overwrite it, bump CURRENT_WORD_LIST_VERSION instead.
const version = CURRENT_WORD_LIST_VERSION
const artifact = resolve(root, 'public', wordListPath(version))
const valuesFile = resolve(root, `src/core/lettergrid/letterValuesV${version}.ts`)
const weightsFile = resolve(root, `src/core/lettergrid/tileWeightsV${version}.ts`)
for (const path of [artifact, valuesFile, weightsFile]) {
  if (existsSync(path)) {
    console.error(`${path} already exists. Word List v${version} is frozen: bump CURRENT_WORD_LIST_VERSION.`)
    process.exit(1)
  }
}

const SOURCE =
  `Copyright 2000-2026 Kevin Atkinson (ESDB/SCOWL), see NOTICES.md; scowl-esdb-${esdbRevision} size60 US+GB sha256:${sha(bigPath)} seeds-size35 sha256:${sha(commonPath)} ` +
  `abbr-from scowl-pre.txt sha256:${sha(prePath)}`

const abbreviations = extractAbbreviations(lines(prePath))
const words = filterScowlWords(lines(bigPath), abbreviations)
const common = new Set(filterScowlWords(lines(commonPath), abbreviations))
const seeds = pickSeedCandidates(words, common)

mkdirSync(dirname(artifact), { recursive: true })
writeFileSync(artifact, encodeWordList({ version, source: SOURCE, words, seeds }))

const values = deriveLetterValues(words)
const table = Object.entries(values)
  .map(([c, v]) => `  ${c}: ${v},`)
  .join('\n')
writeFileSync(
  valuesFile,
  `// Generated by scripts/build-wordlist.ts from Word List v${version}. Frozen: do not edit.\n` +
    `export const LETTER_VALUES_V${version}: Readonly<Record<string, number>> = Object.freeze({\n${table}\n})\n`,
)
const weights = Object.entries(deriveTileWeights(words))
  .map(([c, v]) => `  ${c}: ${v},`)
  .join('\n')
writeFileSync(
  weightsFile,
  `// Generated by scripts/build-wordlist.ts from Word List v${version}. Frozen: do not edit.\n` +
    `export const TILE_WEIGHTS_V${version}: Readonly<Record<string, number>> = Object.freeze({\n${weights}\n})\n`,
)
console.log(`${words.length} words, ${seeds.length} seed candidates -> ${artifact}`)
console.log('Now add the new values to src/core/lettergrid/letterValuesTable.ts and pin the artifact hash in the test.')
